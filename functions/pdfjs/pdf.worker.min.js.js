const UPSTREAM = 'https://cdn.jsdelivr.net/npm/pdfjs-dist@3.11.174/build/pdf.worker.min.js';

export async function onRequestGet(context) {
  const cache = caches.default;
  const cacheKey = new Request(context.request.url, { method: 'GET' });
  const cached = await cache.match(cacheKey);
  if (cached) return cached;

  const upstream = await fetch(UPSTREAM, {
    headers: { 'User-Agent': 'SCPP-Preview-PDFJS/1.0' }
  });
  if (!upstream.ok) return new Response('PDF.js worker non dispoñible', { status: 502 });

  const response = new Response(upstream.body, {
    status: 200,
    headers: {
      'Content-Type': 'application/javascript; charset=utf-8',
      'Cache-Control': 'public, max-age=86400',
      'X-Content-Type-Options': 'nosniff'
    }
  });
  context.waitUntil(cache.put(cacheKey, response.clone()));
  return response;
}
